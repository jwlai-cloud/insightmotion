import type { NextConfig } from "next";

// The stage executes model-generated JavaScript via `new Function` (requires
// 'unsafe-eval'). `connect-src 'self'` is the real teeth here: even if generated
// code reaches `window.fetch`, the browser blocks any request to a non-same-origin
// host, closing the data-exfiltration path. The app itself only calls same-origin
// /api/* (OpenAI is server-side), so this policy does not restrict legitimate use.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "frame-ancestors 'none'",
].join("; ");

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "X-Frame-Options", value: "DENY" },
        ],
      },
    ];
  },
};

export default nextConfig;
